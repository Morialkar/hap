#!/usr/bin/env node
// Generates the vendored, runtime-only gazetteer bundle from the official source archives.
// Usage: node packages/core/scripts/build-gazetteer.mjs /path/to/source-dir
import fs from 'node:fs';
import path from 'node:path';

const sourceDir = process.argv[2];
if (!sourceDir) throw new Error('Usage: build-gazetteer.mjs <source-directory>');

const output = path.resolve('packages/core/src/gazetteer/data.ts');
const admin0 = readShapefile(path.join(sourceDir, 'extracted/admin0/ne_10m_admin_0_countries'));
const admin1 = readShapefile(path.join(sourceDir, 'extracted/admin1/ne_10m_admin_1_states_provinces'));
const cities = readCities(path.join(sourceDir, 'cities1000.txt'));

const countries = admin0.map(({ properties, rings }) => area(clean(properties.FORMAL_FR) || clean(properties.ADMIN), null, rings));
const regions = admin1.map(({ properties, rings }) => area(clean(properties.name_fr) || clean(properties.name_en) || clean(properties.name), clean(properties.admin), rings));
const dataset = {
  metadata: {
    version: 'natural-earth-5.1.1-geonames-cities1000-2026-07-11',
    attributions: [
      { name: 'Natural Earth', license: 'Public domain', url: 'https://www.naturalearthdata.com/' },
      { name: 'GeoNames', license: 'CC BY 4.0', url: 'https://www.geonames.org/' },
    ],
  },
  countries,
  regions,
  cities,
};

fs.writeFileSync(output, `// Generated by packages/core/scripts/build-gazetteer.mjs. Do not edit.\nimport type { GazetteerDataset } from './types';\n\nexport const bundledGazetteerDataset: GazetteerDataset = ${JSON.stringify(dataset)};\n`);
console.log(`Wrote ${output}: ${countries.length} countries, ${regions.length} regions, ${cities.length} cities.`);

function area(name, country, rings) {
  const simplified = rings.map((ring) => simplifyRing(ring, 0.025));
  const values = simplified.flat();
  return { name: clean(name), country: clean(country) || null, bounds: bounds(values), rings: simplified };
}

function readCities(filename) {
  return fs.readFileSync(filename, 'utf8').trim().split('\n').map((line) => {
    const columns = line.split('\t');
    return {
      name: columns[1], asciiName: columns[2],
      lat: Number(columns[4]), lng: Number(columns[5]),
    };
  });
}

function readShapefile(base) {
  const records = readDbf(`${base}.dbf`);
  const buffer = fs.readFileSync(`${base}.shp`);
  const features = [];
  let offset = 100;
  let record = 0;
  while (offset < buffer.length) {
    const length = buffer.readInt32BE(offset + 4) * 2;
    const content = offset + 8;
    const type = buffer.readInt32LE(content);
    if (type === 5) {
      const parts = buffer.readInt32LE(content + 36);
      const points = buffer.readInt32LE(content + 40);
      const partOffset = content + 44;
      const pointOffset = partOffset + parts * 4;
      const starts = Array.from({ length: parts }, (_, index) => buffer.readInt32LE(partOffset + index * 4));
      const coordinates = Array.from({ length: points }, (_, index) => [round(buffer.readDoubleLE(pointOffset + index * 16)), round(buffer.readDoubleLE(pointOffset + index * 16 + 8))]);
      features.push({ properties: records[record], rings: starts.map((start, index) => coordinates.slice(start, starts[index + 1] ?? points)) });
    }
    record += 1;
    offset += 8 + length;
  }
  return features;
}

function readDbf(filename) {
  const buffer = fs.readFileSync(filename);
  const count = buffer.readUInt32LE(4);
  const headerLength = buffer.readUInt16LE(8);
  const recordLength = buffer.readUInt16LE(10);
  const fields = [];
  for (let offset = 32; buffer[offset] !== 0x0d; offset += 32) fields.push({ name: buffer.toString('ascii', offset, offset + 11).replace(/\0.*$/, ''), length: buffer[offset + 16] });
  return Array.from({ length: count }, (_, row) => {
    const values = {};
    let offset = headerLength + row * recordLength + 1;
    for (const field of fields) {
      values[field.name] = buffer.toString('utf8', offset, offset + field.length).trim();
      offset += field.length;
    }
    return values;
  });
}

function simplifyRing(points, tolerance) {
  if (points.length < 4) return points;
  const isClosed = points.at(-1)?.[0] === points[0]?.[0] && points.at(-1)?.[1] === points[0]?.[1];
  const simplified = simplify(isClosed ? points.slice(0, -1) : points, tolerance);
  return isClosed ? [...simplified, simplified[0]] : simplified;
}

function simplify(points, tolerance) {
  const first = points[0]; const last = points.at(-1);
  let index = -1; let greatest = tolerance;
  for (let i = 1; i < points.length - 1; i += 1) { const distance = perpendicularDistance(points[i], first, last); if (distance > greatest) { index = i; greatest = distance; } }
  return index === -1 ? [first, last] : [...simplify(points.slice(0, index + 1), tolerance).slice(0, -1), ...simplify(points.slice(index), tolerance)];
}

function perpendicularDistance([x, y], [x1, y1], [x2, y2]) {
  const numerator = Math.abs((y2 - y1) * x - (x2 - x1) * y + x2 * y1 - y2 * x1);
  return numerator / Math.hypot(y2 - y1, x2 - x1);
}

function bounds(points) { return [Math.min(...points.map(([x]) => x)), Math.min(...points.map(([, y]) => y)), Math.max(...points.map(([x]) => x)), Math.max(...points.map(([, y]) => y))]; }
function clean(value) { return typeof value === 'string' ? value.replace(/\0/g, '').trim() : ''; }
function round(value) { return Number(value.toFixed(5)); }
